"""Whole-export overview of the PS07 dataset: every table, aggregates only.

    python -m vani_persona.analysis.ps07_overview .      # -> docs/findings/dataset_overview.md

Covers seller files, all 269k answered bot calls, every evaluator, the turn
transcripts, the recording sample and the executive calls. No transcript text,
quotes, summaries or identifiers are written. The interpretation lives in
docs/14-dataset-analysis-and-requirements.md.
"""

from __future__ import annotations

import argparse
import collections
import json
import re
import unicodedata
from pathlib import Path

import numpy as np
import pandas as pd

from vani_persona import REPO_ROOT


def _files(root: Path, pattern: str) -> list[Path]:
    files = sorted(root.rglob(pattern))
    if not files:
        raise FileNotFoundError(f"{pattern} not found under {root}")
    return files


def _read(root: Path, pattern: str, **kw) -> pd.DataFrame:
    return pd.concat([pd.read_csv(f, low_memory=False, **kw) for f in _files(root, pattern)], ignore_index=True)


def _pct(x: float) -> str:
    return "n/a" if x is None or pd.isna(x) else f"{x:.1%}"


def _table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = [str(df.index.name or "")] + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, *vals in df.itertuples():
        cells = [
            f"{v:,}" if isinstance(v, (int, np.integer)) and not isinstance(v, bool)
            else floatfmt.format(v) if isinstance(v, float)
            else str(v)
            for v in vals
        ]
        lines.append(f"| {idx} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def icc_anova(df: pd.DataFrame, group: str, y: str) -> float:
    """One-way ANOVA ICC estimator over groups with >= 2 observations."""
    sizes = df.groupby(group)[y].transform("size")
    x = df[sizes >= 2]
    g = x.groupby(group)[y]
    p, k = x[y].mean(), g.size().mean()
    msb = (g.size() * (g.mean() - p) ** 2).sum() / (g.ngroups - 1)
    msw = (g.var(ddof=1) * (g.size() - 1)).sum() / (len(x) - g.ngroups)
    return float((msb - msw) / (msb + (k - 1) * msw))


def parse_evaluators(root: Path) -> pd.DataFrame:
    rows = []
    for f in _files(root, "ps07_evaluator_outputs_*.csv"):
        for ch in pd.read_csv(f, chunksize=50_000, low_memory=False):
            for r in ch.itertuples(index=False):
                d = {"attempt_id": r.attempt_id, "agent": r.eval_agent}
                try:
                    o = json.loads(r.agent_output)
                except (TypeError, ValueError):
                    d["parse_error"] = True
                    rows.append(d)
                    continue
                a = r.eval_agent
                if a == "disposition":
                    d.update(disp=o.get("disposition"), sub=o.get("sub_disposition"))
                elif a == "execdrop":
                    d.update(who=o.get("who_ended_call"), tried=o.get("seller_tried_after_closure"))
                elif a == "ivr":
                    d.update(ivr=o.get("category"))
                elif a == "se_contact":
                    d.update(se=o.get("category"))
                elif a == "incorrect_mf":
                    d.update(imf=o.get("incorrect_mf"))
                elif a == "objections":
                    lst = [x for x in (o.get("objection_analysis") or []) if isinstance(x, dict)]
                    d.update(n_obj=len(lst), obj_cats=[str(x.get("category", "")) for x in lst])
                elif a == "seller_questions":
                    qs = [x for x in (o.get("questions") or []) if isinstance(x, dict)]
                    cats = []
                    for q in qs:
                        c = q.get("category", "")
                        cats += c if isinstance(c, list) else re.findall(r"'([^']+)'", c) or [str(c)]
                    d.update(n_q=len(qs), q_cats=cats)
                elif a == "latency_repetition":
                    lat = o.get("latency") or {}
                    d.update(lat_p50=lat.get("p50_sec"), lat_p95=lat.get("p95_sec"),
                             repeat=lat.get("seller_had_to_repeat_count"), loopy=o.get("is_loopy"),
                             n_turns=o.get("n_turns"))
                elif a == "location_confirmation":
                    pr = o.get("pronunciation") or {}
                    d.update(loc_outcome=o.get("location_outcome"), pron=pr.get("pronunciation_quality"))
                elif a == "topics":
                    d.update(n_topics=len(o.get("discussion_timeline") or []))
                rows.append(d)
    return pd.DataFrame(rows)


def build(root: Path) -> str:
    out: list[str] = [
        "# PS07 dataset overview (generated)",
        "",
        "Generated by `vani_persona.analysis.ps07_overview`. Aggregates only. "
        "Interpretation and requirements: `docs/14-dataset-analysis-and-requirements.md`.",
        "",
    ]

    # ---------------- bot calls
    b = _read(root, "ps07_bot_calls_*.csv", usecols=[
        "attempt_id", "fk_glusr_usr_id", "redis_bucket", "lead_bot_version", "call_attempt_count",
        "call_start_time", "lead_call_duration", "lead_call_summary", "call_recording_url",
        "disposition_label", "meeting_fixed", "has_turn_transcript", "has_evaluator_output"])
    b["t"] = pd.to_datetime(b.call_start_time)
    b["month"] = b.t.dt.strftime("%Y-%m")
    b["hour"] = b.t.dt.hour
    b["attempt"] = b.call_attempt_count.clip(upper=6)
    cps = b.groupby("fk_glusr_usr_id").size()
    icc = icc_anova(b, "fk_glusr_usr_id", "meeting_fixed")
    out += [
        "## 1. Answered bot calls (`ps07_bot_calls_*`)",
        "",
        f"- Calls: {len(b):,}; sellers: {cps.size:,}; calls per seller: mean {cps.mean():.2f}, "
        f"share of sellers with 1 call {(cps == 1).mean():.1%}",
        f"- Meeting-fixed rate: {_pct(b.meeting_fixed.mean())}; intra-seller correlation of meeting_fixed (ICC): {icc:.3f}; "
        f"design effect for seller-level randomization ≈ {1 + (cps.mean() - 1) * icc:.2f}",
        f"- Summary filled: {_pct(b.lead_call_summary.notna().mean())}; recording URL: {_pct(b.call_recording_url.notna().mean())}; "
        f"turn transcript: {_pct(b.has_turn_transcript.mean())}; any evaluator: {_pct(b.has_evaluator_output.mean())}",
        "",
        "### By month",
        "",
        _table(b.groupby("month").agg(calls=("attempt_id", "size"), meeting_fixed=("meeting_fixed", "mean"),
                                      median_duration_s=("lead_call_duration", "median"))),
        "",
        "### By bot version (campaign)",
        "",
        _table(b.groupby("lead_bot_version").agg(
            calls=("attempt_id", "size"), meeting_fixed=("meeting_fixed", "mean"),
            first_attempt_share=("call_attempt_count", lambda s: (s == 1).mean()),
            recordings=("call_recording_url", lambda s: s.notna().mean()),
            transcripts=("has_turn_transcript", "mean"),
            first_month=("month", "min"), last_month=("month", "max"),
        ).sort_values("calls", ascending=False)),
        "",
        "### By lead bucket (`redis_bucket`, top 10)",
        "",
        _table(b.groupby("redis_bucket").agg(calls=("attempt_id", "size"), meeting_fixed=("meeting_fixed", "mean"))
               .sort_values("calls", ascending=False).head(10)),
        "",
        "### By attempt number",
        "",
        _table(b.groupby("attempt").agg(calls=("attempt_id", "size"), meeting_fixed=("meeting_fixed", "mean"))
               .rename_axis("attempt (6 = 6+)")),
        "",
        "### By hour of day (IST)",
        "",
        _table(b[b.hour.between(9, 20)].groupby("hour").agg(
            calls=("attempt_id", "size"), meeting_fixed=("meeting_fixed", "mean"),
            first_attempt_share=("call_attempt_count", lambda s: (s == 1).mean()),
            not_interested=("disposition_label", lambda s: (s == "Not Interested").mean()))),
        "",
        "### Duration by disposition (seconds)",
        "",
        _table(b.groupby("disposition_label").lead_call_duration.describe()[["count", "25%", "50%", "75%"]]),
        "",
    ]

    # small September trials vs main_vani with the same attempt x bucket mix
    sep = b[b.t.dt.month == 9]
    ref = sep[sep.lead_bot_version == "main_vani"].assign(a=lambda d: d.call_attempt_count.clip(upper=4)) \
        .groupby(["a", "redis_bucket"]).meeting_fixed.mean()
    trial_rows = []
    for v in ["personalis", "base_vani", "summary_va"]:
        x = sep[sep.lead_bot_version == v]
        if x.empty:
            continue
        exp = [ref.get((min(a, 4), bk), np.nan) for a, bk in zip(x.call_attempt_count, x.redis_bucket)]
        trial_rows.append({"version": v, "calls": len(x), "days": x.t.dt.date.nunique(),
                           "observed_mf": x.meeting_fixed.mean(), "expected_mf_main_vani_mix": float(np.nanmean(exp))})
    if trial_rows:
        out += [
            "### September trial versions vs main_vani (same attempt × lead-bucket mix; NOT randomized)",
            "",
            _table(pd.DataFrame(trial_rows).set_index("version")),
            "",
        ]

    # ---------------- evaluators
    e = parse_evaluators(root)
    ev = lambda a: e[e.agent == a].drop_duplicates("attempt_id", keep="last").merge(  # noqa: E731
        b[["attempt_id", "meeting_fixed", "call_attempt_count"]], on="attempt_id", how="left")
    cov = (e.groupby("agent").attempt_id.nunique() / len(b)).sort_values(ascending=False)
    out += [
        "## 2. Evaluator outputs (`ps07_evaluator_outputs_*`)",
        "",
        f"- Rows: {len(e):,}; JSON parse errors: {int(e.get('parse_error', pd.Series(dtype=bool)).fillna(False).sum())}",
        "",
        _table(pd.DataFrame({"calls_covered": e.groupby("agent").attempt_id.nunique(), "share_of_bot_calls": cov})
               .sort_values("calls_covered", ascending=False)),
        "",
    ]
    d = ev("disposition")
    out += [
        "### Detailed disposition",
        "",
        _table(d.disp.value_counts(normalize=True).rename("share").to_frame()),
        "",
        _table(d["sub"].value_counts(normalize=True).rename("share").to_frame().rename_axis("sub_disposition")),
        "",
        "Sub-disposition by attempt number (share of evaluated calls):",
        "",
        _table(pd.crosstab(d.call_attempt_count.clip(upper=4), d["sub"], normalize="index")[
            [c for c in ["no_response", "dropped_after_indiamart_identity", "dropped_after_seller_identity",
                         "dropped_mid_pitch", "flat_refusal_or_no_requirement", "none"] if c in set(d["sub"])]
        ].rename_axis("attempt (4 = 4+)")),
        "",
        f"- Agreement with `meeting_fixed` label: evaluator says meeting but label 0: "
        f"{_pct(((d.disp.isin(['meeting_fixed', 'online_meeting_fixed'])) & (d.meeting_fixed == 0)).mean())}; "
        f"label 1 but evaluator not: {_pct(((~d.disp.isin(['meeting_fixed', 'online_meeting_fixed'])) & (d.meeting_fixed == 1)).mean())}",
        "",
    ]
    x = ev("execdrop")
    i = ev("ivr")
    s = ev("se_contact")
    m = ev("incorrect_mf")
    out += [
        "### Other evaluators",
        "",
        f"- `execdrop` ({len(x):,}): who ended: {x.who.value_counts(normalize=True).round(3).to_dict()}; "
        f"seller still trying after closure: {_pct((x.tried == 'YES').mean())}",
        f"- `ivr` ({len(i):,}): {i.ivr.value_counts(normalize=True).round(3).to_dict()}",
        f"- `se_contact` ({len(s):,}): {s.se.value_counts(normalize=True).round(3).to_dict()}; "
        f"meeting rate by category: {s.groupby('se').meeting_fixed.mean().round(3).to_dict()}",
        f"- `incorrect_mf` ({len(m):,}): flagged incorrect {_pct(m.imf.mean())}",
    ]
    o = ev("objections")
    oc = collections.Counter(c for v in o.obj_cats.dropna() for c in v if c)
    q = ev("seller_questions")
    qc = collections.Counter(c for v in q.q_cats.dropna() for c in v if c)
    loc = ev("location_confirmation")
    out += [
        f"- `objections` ({len(o):,}; ≥1 objection in {_pct((o.n_obj > 0).mean())}): "
        + ", ".join(f"{k} {v}" for k, v in oc.most_common(12)),
        f"- `seller_questions` ({len(q):,}; ≥1 question in {_pct((q.n_q > 0).mean())}): "
        + ", ".join(f"{k} {v}" for k, v in qc.most_common(12)),
        f"- `location_confirmation` ({len(loc):,}): {loc.loc_outcome.value_counts(normalize=True).round(3).to_dict()}; "
        f"bot pronunciation: {loc.pron.value_counts(normalize=True).round(3).to_dict()}",
        "",
    ]
    lat = ev("latency_repetition")
    lat["p50_bucket"] = pd.cut(lat.lat_p50, [-100, 1, 1.5, 2, 3, 100], labels=["≤1s", "1–1.5s", "1.5–2s", "2–3s", ">3s"])
    out += [
        "### Bot latency and repetition (`latency_repetition`; same calls as the turn transcripts)",
        "",
        f"- Calls: {len(lat):,}; per-call median bot lag: median {lat.lat_p50.median():.2f}s, p90 {lat.lat_p50.quantile(0.9):.2f}s; "
        f"negative lags (timestamp artefacts): {_pct((lat.lat_p50 < 0).mean())}",
        f"- Seller had to repeat ≥ 1×: {_pct((lat.repeat > 0).mean())}; loopy bot: {_pct(lat.loopy.mean())}",
        "",
        "Meeting rate by the call's median bot lag (correlational):",
        "",
        _table(lat.groupby("p50_bucket", observed=True).agg(calls=("attempt_id", "size"),
                                                           meeting_fixed=("meeting_fixed", "mean"))),
        "",
    ]

    # ---------------- turns / language
    t = _read(root, "ps07_call_turns.csv")
    letters = collections.Counter()
    for txt in t.text.fillna(""):
        for ch in txt:
            if ch.isalpha():
                letters[unicodedata.name(ch, "?").split()[0]] += 1
    tot = sum(letters.values())
    seller = t[t.speaker == "seller"].assign(l=lambda d: d.text.fillna("").str.lower())
    markers = {
        "Tamil": r"\b(?:sollunga|illa|illai|enna|vanakkam|seri|romba)\b",
        "Bengali": r"\b(?:ami|bolchi|achhe|korbo|apni)\b",
        "Gujarati": r"\b(?:che|chhe|nathi|kem|tamare)\b",
        "Telugu": r"\b(?:cheppandi|ledu|undi|avunu)\b",
        "mostly English (≥5 Latin words, no Hindi function words)": r"^(?!.*\b(?:hai|nahi|kya|haan|ji|main|aap)\b)(?:[a-z']+ ){4,}[a-z']+$",
    }
    n_calls = t.attempt_id.nunique()
    out += [
        "## 3. Turn transcripts (`ps07_call_turns.csv`)",
        "",
        f"- Turns: {len(t):,}; calls: {n_calls:,}; speakers: {t.speaker.value_counts().to_dict()}",
        "- Letters by script: " + ", ".join(f"{k} {v / tot:.2%}" for k, v in letters.most_common(4)),
        "- Calls with romanized regional-language markers (rough lexical heuristic): "
        + "; ".join(
            f"{k} {seller[seller.l.str.contains(p, regex=True)].attempt_id.nunique() / n_calls:.1%}"
            for k, p in markers.items()
        ),
        "",
    ]

    # ---------------- recording sample
    rs = _read(root, "ps07_recording_sample_5000.csv")
    out += [
        "## 4. Recording sample (`ps07_recording_sample_5000.csv`)",
        "",
        f"- Calls: {len(rs):,}; with turn transcripts: {int(rs.has_turn_transcript.sum()):,}; recording URL filled: {_pct(rs.call_recording_url.notna().mean())}",
        f"- Dispositions: {rs.disposition_label.value_counts().to_dict()}",
        f"- Bot versions: {rs.lead_bot_version.value_counts().to_dict()}",
        "",
    ]

    # ---------------- seller file
    sf = _read(root, "ps07_seller_files_part*.csv")
    nn = sf.notna().mean()
    flags = ["asked_if_talking_to_bot", "showed_frustration", "already_in_touch_with_executive", "do_not_call_requested"]
    out += [
        "## 5. Seller file (`ps07_seller_files_part*`)",
        "",
        f"- Sellers: {len(sf):,}; columns: {sf.shape[1]}; duplicate ids: {int(sf.fk_glusr_usr_id.duplicated().sum())}",
        f"- Engagement block (`eng_*`) present: {_pct(nn.get('eng_call_attempts_90d'))}; "
        f"`past_dispositions_detailed`: {_pct(nn.get('past_dispositions_detailed'))}; "
        f"`past_objections`: {_pct(nn.get('past_objections'))}; `past_questions_asked`: {_pct(nn.get('past_questions_asked'))}",
        "- Behaviour flags (share of sellers where evaluated / = 1): "
        + "; ".join(f"`{f}` {_pct(sf[f].notna().mean())} / {_pct((sf[f] == 1).mean())}" for f in flags),
        f"- Business type: {sf.business_type.value_counts(normalize=True).round(3).head(4).to_dict()}",
        f"- Turnover: {sf.annual_turnover.value_counts(normalize=True).round(3).head(4).to_dict()}",
        "- Note: bot-history columns aggregate Apr–Sep, including each call itself and later calls (leakage for any per-call model).",
        "",
    ]

    # ---------------- executive calls
    ex = _read(root, "ps07_executive_calls.csv")
    ex["t"] = pd.to_datetime(ex.call_start_time)
    w = b[(b.t >= "2026-08-01") & (b.t < "2026-09-15")][["attempt_id", "fk_glusr_usr_id", "t", "meeting_fixed"]]
    ans = ex[ex.status == "Answered"][["fk_glusr_usr_id", "t"]].rename(columns={"t": "tx"})
    j = w.merge(ans, on="fk_glusr_usr_id", how="left")
    j["after"] = (j.tx > j.t) & (j.tx <= j.t + pd.Timedelta(days=14))
    follow = j.groupby(["attempt_id", "meeting_fixed"]).after.any().reset_index().groupby("meeting_fixed").after.mean()
    out += [
        "## 6. Executive calls (`ps07_executive_calls.csv`)",
        "",
        f"- Calls: {len(ex):,}; sellers: {ex.fk_glusr_usr_id.nunique():,}; window {ex.t.min():%Y-%m-%d} → {ex.t.max():%Y-%m-%d}; "
        f"answered {_pct((ex.status == 'Answered').mean())}",
        f"- Modules: {ex.module.value_counts().head(6).to_dict()}",
        f"- Bot calls 1 Aug–14 Sep followed by an answered executive call within 14 days: "
        f"meeting fixed {_pct(follow.get(1))} vs not fixed {_pct(follow.get(0))}",
        "",
    ]
    return "\n".join(out) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("root", type=Path, nargs="?", default=REPO_ROOT)
    p.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "findings" / "dataset_overview.md")
    a = p.parse_args()
    a.out.write_text(build(a.root))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
