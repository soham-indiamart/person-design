"""Persona discovery: historical calls -> validated behavioural segments + reports.

    python -m vani_persona.segmentation.pipeline data/raw

Outputs:
  docs/findings/segmentation_report.md     (aggregate statistics only: safe to commit)
  docs/findings/outcome_association.md
  artifacts/segmentation.joblib            (model, gitignored)
  artifacts/persona_prototypes.yaml        (segment prototypes to seed persona YAMLs)
  data/derived/segments.csv                (call_id -> segment, gitignored)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import yaml
from scipy.stats import chi2_contingency

from vani_persona import REPO_ROOT
from vani_persona.config import load_thresholds
from vani_persona.features.registry import FEATURES, language_features, segment_features
from vani_persona.ingest.sources import SOURCES, load_calls_from
from vani_persona.segmentation.outcomes import adjusted_rates
from vani_persona.segmentation.preprocess import StrataResidualizer, build_frame, select_segment_features
from vani_persona.segmentation.validate import KReport, choose_k, evaluate_k

log = logging.getLogger(__name__)


def eligibility(df: pd.DataFrame, cfg: dict) -> tuple[pd.Series, dict[str, int]]:
    """Calls usable for discovery. Short calls are excluded, never labelled as 'impatient'."""
    reasons: dict[str, pd.Series] = {
        "technical failure / wrong party / no response": df["disposition_class"].isin(
            ["technical_failure", "wrong_party", "no_response"]
        ),
        f"< {cfg['min_seller_turns']} seller turns": df["n_seller_turns"] < cfg["min_seller_turns"],
        f"< {cfg['min_seller_tokens']} seller tokens": (
            df["seller_mean_tokens"].fillna(0) * df["n_seller_turns"] < cfg["min_seller_tokens"]
        ),
        f"mean ASR confidence < {cfg['min_asr_confidence']}": (
            df["mean_asr_confidence"].notna() & (df["mean_asr_confidence"] < cfg["min_asr_confidence"])
        ),
    }
    excluded = pd.Series(False, index=df.index)
    counts = {}
    for name, mask in reasons.items():
        counts[name] = int((mask & ~excluded).sum())
        excluded |= mask
    return ~excluded, counts


def cramers_v(a: pd.Series, b: pd.Series) -> float:
    table = pd.crosstab(a, b)
    if min(table.shape) < 2:
        return 0.0
    chi2 = chi2_contingency(table, correction=False)[0]
    return float(np.sqrt(chi2 / (table.values.sum() * (min(table.shape) - 1))))


def describe_segments(df: pd.DataFrame, x: np.ndarray, labels: np.ndarray, feats: list[str], z_thr: float) -> list[dict]:
    out = []
    zdf = pd.DataFrame(x, columns=feats)
    for s in sorted(np.unique(labels)):
        mask = labels == s
        z = zdf[mask].mean()
        distinct = z[abs(z) >= z_thr].sort_values(key=abs, ascending=False)
        sub = df[mask]
        out.append(
            {
                "segment": int(s),
                "n_calls": int(mask.sum()),
                "share": float(mask.mean()),
                "distinctive": {f: round(float(v), 2) for f, v in distinct.items()},
                "raw_median": {f: round(float(sub[f].median()), 3) for f in feats if sub[f].notna().any()},
                "detail_mean_vs_all": {
                    f: (round(float(sub[f].mean()), 3), round(float(df[f].mean()), 3))
                    for f, spec in FEATURES.items()
                    if spec.role == "detail" and sub[f].notna().any()
                },
                "language_mix": sub["language_hint"].value_counts(normalize=True).round(3).head(5).to_dict(),
                "language_features_median": {
                    f: round(float(sub[f].median()), 3) for f in language_features() if sub[f].notna().any()
                },
                "disposition_mix": sub["disposition_class"].value_counts(normalize=True).round(3).to_dict(),
            }
        )
    return out


def prototypes(df: pd.DataFrame, labels: np.ndarray, feats: list[str]) -> dict:
    """Center = segment median; scale = robust overall spread. Seeds `matching.prototype` in persona YAMLs."""
    out = {}
    for s in sorted(np.unique(labels)):
        sub = df[labels == s]
        proto = {}
        for f in feats:
            col = df[f].astype(float)
            spread = float((col.quantile(0.75) - col.quantile(0.25)) / 1.349) or float(col.std() or 1.0)
            proto[f] = {"center": round(float(sub[f].median()), 4), "scale": round(spread, 4)}
        out[f"segment_{s}"] = proto
    return out


def write_segmentation_report(path: Path, ctx: dict) -> None:
    lines = [
        "# Segmentation report (generated)",
        "",
        f"Run `{ctx['run_id']}`, generated by `vani_persona.segmentation.pipeline` from `{ctx['source']}`. "
        "Aggregates only; no transcript text. Thresholds come from `config/thresholds.yaml` and are tunable "
        "(`validated: false`).",
        "",
        "## Data used",
        "",
        f"- Calls loaded: {ctx['n_total']}",
        f"- Eligible for discovery: {ctx['n_eligible']}",
        "- Exclusions (first matching reason):",
        *[f"  - {k}: {v}" for k, v in ctx["exclusions"].items()],
        f"- Timestamps available: {ctx['ts_share']:.0%} of eligible calls",
        "",
        "## Features",
        "",
        f"- Used for clustering: {', '.join(f'`{f}`' for f in ctx['features'])}",
        *[f"- Dropped `{f}`: {why}" for f, why in ctx["dropped"].items()],
        "- Language features are excluded from clustering by design (language is a separate runtime axis).",
        "",
        "## Candidate k",
        "",
        "| k | BIC | silhouette | min share | bootstrap ARI | temporal ARI | k-means agreement | min centroid dist | pass | failures |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in ctx["reports"]:
        t = "n/a" if r.temporal_ari is None else f"{r.temporal_ari:.2f}"
        lines.append(
            f"| {r.k} | {r.bic:.0f} | {r.silhouette:.3f} | {r.min_share:.1%} | {r.bootstrap_ari:.2f} | {t} | "
            f"{r.kmeans_agreement_ari:.2f} | {r.min_centroid_distance:.2f} | {'yes' if r.passed else 'no'} | "
            f"{'; '.join(r.failures) or '-'} |"
        )
    lines.append("")
    chosen: KReport | None = ctx["chosen"]
    if chosen is None:
        lines += [
            "## Result: NO persona library supported",
            "",
            "No k in the allowed range passed every validation gate, so personas are **not** forced. Next steps: "
            "check the feature missingness above, review the lexicons against a sample of transcripts, "
            "collect more calls, or add timestamp/acoustic features. VANI keeps the neutral default.",
        ]
    else:
        lines += [
            f"## Result: k = {chosen.k} (pending human interpretability review)",
            "",
            "Distinctive features are mean residualized z-scores (|z| >= threshold). They are relative to "
            "comparable calls in the same campaign/objective/language stratum.",
            "",
        ]
        for seg in ctx["segments"]:
            lines += [
                f"### Segment {seg['segment']} — {seg['n_calls']} calls ({seg['share']:.1%})",
                "",
                "- Distinctive: "
                + (", ".join(f"`{f}` {v:+.2f}" for f, v in seg["distinctive"].items()) or "none above threshold"),
                f"- Raw medians: {seg['raw_median']}",
                "- Detail features, segment mean vs all calls: "
                + ", ".join(f"`{f}` {a} vs {b}" for f, (a, b) in seg["detail_mean_vs_all"].items()),
                f"- Language hint mix (descriptive only): {seg['language_mix']}",
                f"- Disposition mix (descriptive only): {seg['disposition_mix']}",
                "",
            ]
        lines += [
            "## Proxy / stereotyping check",
            "",
            "Cramér's V between segment and non-behavioural attributes. Values above 0.5 mean the segment may be "
            "a proxy for language or category rather than for behaviour, and need review before approval.",
            "",
            *[f"- {k}: {v:.2f}{'  ⚠ review' if v > 0.5 else ''}" for k, v in ctx["proxy"].items()],
            "",
            "## Approval checklist (human)",
            "",
            "- [ ] Each segment can be described in behavioural terms a sales lead recognises",
            "- [ ] 20 random transcripts per segment read; the description holds for most of them",
            "- [ ] No segment is a proxy for language, region or category (see above)",
            "- [ ] Each approved segment has a distinct, actionable communication strategy (otherwise merge)",
        ]
    path.write_text("\n".join(lines) + "\n")


def write_outcome_report(path: Path, table: pd.DataFrame | None, note: str) -> None:
    lines = [
        "# Outcome association by segment (generated, descriptive)",
        "",
        "All historical calls used the same VANI style. These numbers show where that uniform style does better "
        "or worse **after adjusting** for campaign, objective, language, category, agent version and hour. "
        "They are **not** evidence that any persona improves outcomes; only the A/B test can show that.",
        "",
        note,
        "",
    ]
    if table is not None:
        lines += [
            "| segment | calls | raw rate | adjusted rate | 95% CI (bootstrap) |",
            "|---|---|---|---|---|",
            *[
                f"| {r.segment} | {r.n_calls} | {r.raw_rate:.1%} | {r.adjusted_rate:.1%} | "
                f"{r.ci95_low:.1%} – {r.ci95_high:.1%} |"
                for r in table.itertuples()
            ],
        ]
    path.write_text("\n".join(lines) + "\n")


def run(
    raw: Path, findings: Path, artifacts: Path, derived: Path, n_boot: int = 200, seed: int = 0, source: str = "generic"
) -> dict:
    cfg = load_thresholds()["segmentation"]
    calls = load_calls_from(raw, source)
    df = build_frame(calls)
    ok, exclusions = eligibility(df, cfg)
    d = df[ok].reset_index(drop=True)
    if len(d) < 200:
        raise SystemExit(f"Only {len(d)} eligible calls; too few for discovery (need >= 200, ideally thousands).")

    excluded = cfg.get("exclude_features") or {}
    candidates = [f for f in segment_features() if f not in excluded]
    feats, dropped = select_segment_features(d, candidates, cfg["max_feature_missing"])
    dropped = {**{f: f"excluded by config: {why}" for f, why in excluded.items()}, **dropped}
    resid = StrataResidualizer(feats, min_stratum_n=cfg["min_stratum_n"]).fit(d)
    x = resid.transform(d)
    order = None
    if d["started_at"].notna().mean() > 0.9:
        order = pd.to_datetime(d["started_at"], utc=True).astype("int64").to_numpy()

    # Deterministic run id: same calls + features + thresholds -> same id. Personas cite it as evidence.
    fingerprint = hashlib.sha256(
        json.dumps([sorted(d["call_id"]), feats, cfg], sort_keys=True, default=str).encode()
    ).hexdigest()[:10]

    reports, models = [], {}
    lo, hi = cfg["k_range"]
    for k in range(lo, hi + 1):
        rep, model = evaluate_k(x, k, order, cfg, seed)
        reports.append(rep)
        models[k] = model
        log.info("k=%d passed=%s %s", k, rep.passed, rep.failures)
    chosen = choose_k(reports)

    ctx = {
        "run_id": f"seg-{fingerprint}",
        "source": f"{raw.resolve().name or raw} (loader: {source})",
        "n_total": len(df),
        "n_eligible": len(d),
        "exclusions": exclusions,
        "ts_share": float(d["has_timestamps"].mean()),
        "features": feats,
        "dropped": dropped,
        "reports": reports,
        "chosen": chosen,
    }
    findings.mkdir(parents=True, exist_ok=True)
    artifacts.mkdir(parents=True, exist_ok=True)
    derived.mkdir(parents=True, exist_ok=True)

    if chosen is not None:
        labels = models[chosen.k].predict(x)
        d["segment"] = labels
        ctx["segments"] = describe_segments(d, x, labels, feats, cfg["distinguishing_z"])
        ctx["proxy"] = {
            c: cramers_v(d["segment"], d[c])
            for c in ["language_hint", "seller_category", "region", "campaign_id", "lead_type"]
            if d[c].nunique() > 1
        }
        joblib.dump(
            {"residualizer": resid, "model": models[chosen.k], "features": feats, "k": chosen.k, "run_id": ctx["run_id"]},
            artifacts / "segmentation.joblib",
        )
        (artifacts / "persona_prototypes.yaml").write_text(
            yaml.safe_dump({"run_id": ctx["run_id"], **prototypes(d, labels, feats)}, sort_keys=False)
        )
        d[["call_id", "segment"]].to_csv(derived / "segments.csv", index=False)
        try:
            table = adjusted_rates(d, n_boot=n_boot, seed=seed)
            note = f"Outcome: `objective_achieved`. Calls with a known outcome: {int(d['objective_achieved'].notna().sum())}."
        except ValueError as e:
            table, note = None, f"Outcome model not fitted: {e}"
        write_outcome_report(findings / "outcome_association.md", table, note)
    write_segmentation_report(findings / "segmentation_report.md", ctx)
    return ctx


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("raw", type=Path, nargs="?", default=REPO_ROOT / "data" / "raw")
    p.add_argument("--findings", type=Path, default=REPO_ROOT / "docs" / "findings")
    p.add_argument("--artifacts", type=Path, default=REPO_ROOT / "artifacts")
    p.add_argument("--derived", type=Path, default=REPO_ROOT / "data" / "derived")
    p.add_argument("--bootstrap", type=int, default=200, help="bootstrap rounds for outcome CIs")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--source", choices=SOURCES, default="generic")
    a = p.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    ctx = run(a.raw, a.findings, a.artifacts, a.derived, a.bootstrap, a.seed, a.source)
    chosen = ctx["chosen"]
    print(f"run {ctx['run_id']}: eligible calls: {ctx['n_eligible']}; chosen k: {chosen.k if chosen else 'none (no k passed)'}")
    print(f"report: {a.findings / 'segmentation_report.md'}")


if __name__ == "__main__":
    main()
